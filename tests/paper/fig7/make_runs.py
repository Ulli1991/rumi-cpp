#!/usr/bin/env python3
"""BIFROST Fig. 7 timing test (Rantala et al. 2023, MNRAS 522, 5180, Sec. 4.2): configs and gpudev job scripts.

BIFROST: SCIC star clusters (App. A) of N = 1e4, 1e5, 1e6 with f_bin = 10 ... 100 %, one integration interval of
T = 1e-3 Myr on one Raven node (4 A100), accuracy parameters of Sec. 4.1: eta = 0.2 (free-fall, fly-by), 0.1 (jerk,
gradient), eta_GBS = 1e-10, LogH end-time tolerance 1e-4 (gbs.cpp default), r_ngb = 1e-3 pc, r_ngb,max = 0.1 pc
(Sec. 3.3). Measured: 720, 67, 1.5 Myr per 24 h -> 0.120, 1.29, 57.6 s per interval; +25 %, +24 %, +3 % from
f_bin = 10 % to 100 %.

The paper does not give a_min, a_max, the IMF upper mass, the stellar age or metallicity of the timing clusters.
Our choices (stated in the report and in configs/README-style comments below):
  * Population: Kroupa (2001) IMF evolved to 1 Gyr at Z = 0.0002 with SSE -- the population of BIFROST's own
    binary cluster (Sec. 5.4, "before 1 Gyr of binary stellar evolution"), our SSE settings of config.txt.
  * r_h from the SCIC mass-size relation (App. A eq. A2, Brown & Gnedin 2021) of the evolved cluster mass.
  * a in [0.25, 1000] AU, flat in log a, thermal e: a_min calibrated on BIFROST Sec. 5.4 ("the energy of the binary
    population exceeds the energy of a f_bin = 0 % cluster by a factor of ~7"): our IC of that cluster (N = 2e5,
    r_h = 3.1 pc, f_bin = 0.5) gives E_bin/|E_obj| = 43.9, 9.5, 6.5 for a_min = 0.03, 0.2, 0.3 AU (a_max = 1000 AU).
    a_max = 1000 AU (~5 r_ngb) keeps r_break = 3 a_max = 0.015 pc well below the central inter-particle distance
    (0.08-0.12 pc for these clusters), as App. A requires ("a_max << r_h").
  * Pairing: BINARY_POP = bifrost (flat q in [0.1, 1) above 5 M_sun, closest-mass pick, random below); no BSE: the
    pericentre check (r_p > R1 + R2, TDE radius / ISCO for compact objects, t_GW > 0.01 Myr) stands in for SCIC's
    BSE merger pass. IC_R_BREAK = 3 (r_break = 3 a_max).

Usage: make_runs.py <run_dir> <exe>   (writes configs/ next to this script and job_*.sh into run_dir)
"""
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

BASE = dict(
    TEST_CASE="plummer", INTEGRATOR="hhs",
    DT_MAX_MYR="1.0e-3", DT_MIN_MYR="1.0e-14",
    # BIFROST Sec. 4.1 accuracy parameters
    ETA_FF="0.2", ETA_FB="0.2", ETA_GRAD="0.1", ETA_JERK="0.1", ETA_GBS="1e-10",
    R_NGB="1e-3", R_NGB_MAX="0.1",
    # Repository defaults (config.txt) for everything the paper does not set
    SOFTENING_PC="0", SERIAL_N2_GPU="16384",
    COLLISIONAL="true", ETA_PERT="0.02", ETA_RESTART="1e-8", N_ORB_SECULAR="3", M_PN="5.0", PN_ORDER="31",
    R_ESCAPE_RH="100.0", MSTAR_THRESHOLD="8", SSE_ENABLED="false", SSE_METALLICITY="0.0002",
    SSE_WIND_MODEL="VINK", SSE_REMNANT_MODEL="BELCZYNSKI02", SSE_PPISN_MODEL="STRONG", SSE_ECSN_MODEL="ON",
    SSE_MXNS="2.5", SSE_FLBV="1.5",
    # SCIC cluster (App. A)
    PLUMMER_R_HALF="mass_size", PLUMMER_SEED="42", PLUMMER_MASS_DIST="kroupa_evolved", PLUMMER_AGE_GYR="1.0",
    PLUMMER_METALLICITY="0.0002", BINARY_A_MIN_AU="0.25", BINARY_A_MAX_AU="1000", BINARY_POP="bifrost",
    BINARY_PERI_CHECK="true", IC_R_BREAK="3",
    PRINT_INTERVAL="1", PROFILING="true",
)

# (N, f_bin, intervals, per-run timeout [s]); 10 intervals for the median, step 1 = BIFROST's measurement
RUNS = [(10000, f, 10, 120) for f in (0.1, 0.5, 1.0)] + [(100000, f, 10, 270) for f in (0.1, 0.5, 1.0)] + \
       [(1000000, 0.1, 1, 840)]
CM = {"cmoff": "false", "cmon": "true"}


def name(n, f, cm):
    return f"n{n:.0e}".replace("+0", "").replace("+", "") + f"_f{int(round(100 * f)):03d}_{cm}"


def write_configs():
    d = HERE / "configs"
    d.mkdir(exist_ok=True)
    out = []
    for n, f, steps, tmo in RUNS:
        for cm, flag in CM.items():
            cfg = dict(BASE, PLUMMER_N=str(n), BINARY_FRAC=str(f), TOTAL_TIME_MYR=f"{steps}e-3",
                       FLYBY_CM_VELOCITY=flag)
            p = d / f"{name(n, f, cm)}.txt"
            p.write_text("# BIFROST Fig. 7 timing run, generated by make_runs.py\n" +
                         "".join(f"{k} = {v}\n" for k, v in cfg.items()))
            out.append((p, n, tmo))
    return out


JOB = """#!/bin/bash -l
#SBATCH -o ./{job}.out.%j
#SBATCH -e ./{job}.err.%j
#SBATCH -D ./
#SBATCH -J {job}
#SBATCH --partition=gpudev
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=4
#SBATCH --gres=gpu:a100:4
#SBATCH --cpus-per-task=18
#SBATCH --mem=64000
#SBATCH --time=00:15:00
module purge
module load gcc/13 cuda/12.6 openmpi_gpu/5.0
export OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK OMP_PROC_BIND=spread OMP_PLACES=threads OMPI_MCA_mpi_cuda_support=1
"""
RUN = """mkdir -p {r} && cd {r} && cp ../configs/{r}.txt config.txt
timeout {tmo} srun ../{exe} --config config.txt --kokkos-map-device-id-by=mpi_rank > ../{r}.log 2>&1
echo "{r} exit $?"
cd ..
"""


def main():
    run_dir, exe = Path(sys.argv[1]), Path(sys.argv[2])
    run_dir.mkdir(parents=True, exist_ok=True)
    cfgs = write_configs()
    shutil.copytree(HERE / "configs", run_dir / "configs", dirs_exist_ok=True)
    shutil.copy2(exe, run_dir / exe.name)
    # Jobs within the 15 min gpudev limit: all 1e4 runs; 1e5 by c.o.m. setting; 1e6 one per job
    groups = {"j_n1e4": [c for c in cfgs if c[1] == 10000]}
    for cm in CM:
        groups[f"j_n1e5_{cm}"] = [c for c in cfgs if c[1] == 100000 and c[0].stem.endswith(cm)]
        groups[f"j_n1e6_{cm}"] = [c for c in cfgs if c[1] == 1000000 and c[0].stem.endswith(cm)]
    for job, members in groups.items():
        text = JOB.format(job=job) + "".join(RUN.format(r=p.stem, tmo=tmo, exe=exe.name) for p, _, tmo in members)
        (run_dir / f"{job}.sh").write_text(text)
        print(f"{job}.sh: {[p.stem for p, _, _ in members]}")


if __name__ == "__main__":
    main()
